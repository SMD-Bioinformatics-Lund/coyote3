"""Application SDK values, independent of HTTP envelopes and storage drivers."""

from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from coyote3.domain.finding_types import normalize_finding_kind


class SampleRecord(BaseModel):
    """A detached sample snapshot; reading it does not authorize a later operation."""

    model_config = ConfigDict(frozen=True)

    id: str
    name: str
    assay_id: str
    environment: str | None
    attributes: dict[str, Any]


class FindingPage(BaseModel):
    """Ordered findings selected by the clinical service, with its pagination values."""

    model_config = ConfigDict(frozen=True)

    items: list[dict[str, Any]]
    pagination: dict[str, Any] = Field(default_factory=dict)


class FlagChange(BaseModel):
    """Review-state change for findings belonging to one authorized sample."""

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    resource_ids: list[str] = Field(min_length=1, max_length=10000)
    flag: Literal["interesting", "false_positive", "irrelevant", "blacklisted"]
    value: bool


class TierChange(BaseModel):
    """Explicit tier assignment or removal, retaining existing clinical validation."""

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    resource_type: Literal["small_variant", "cnv", "fusion", "translocation"]
    resource_ids: list[str] = Field(max_length=10000)
    tier: int = Field(ge=1, le=4)
    apply: bool = True
    include_automatic_text: bool = False
    deactivation_scope: Literal["diagnosis", "group"] = "diagnosis"

    @model_validator(mode="after")
    def validate_deactivation_scope(self) -> "TierChange":
        """Reject group deactivation intent on a tier assignment."""
        if self.apply and self.deactivation_scope != "diagnosis":
            raise ValueError("Group deactivation requires apply=false")
        return self

    @field_validator("resource_type", mode="before")
    @classmethod
    def normalize_resource_type(cls, value: str) -> str:
        """Retain the existing finding-family input spellings before canonical validation."""
        return normalize_finding_kind(value)


class ReportTrial(BaseModel):
    """Hold an unsaved alternate report and its PDF entirely in memory."""

    html: str
    pdf: bytes
    filename: str
    snapshot_count: int
    reporting_warning: str | None = None


class ReportPreview(BaseModel):
    """Rendered report and the fingerprint required to save the reviewed inputs."""

    model_config = ConfigDict(frozen=True)

    template: str
    context: dict[str, Any]
    html: str
    snapshot_rows: list[dict[str, Any]]
    fingerprint: str
    sample: dict[str, Any] = Field(default_factory=dict)
    snapshot_count: int = 0


class SavedReport(BaseModel):
    """Saved report identity and artifact locations returned by the reporting service."""

    model_config = ConfigDict(frozen=True)

    id: str
    storage_id: str
    file: str
    pdf_file: str | None
    snapshot_count: int
    sample: dict[str, Any] = Field(default_factory=dict)


class IngestResult(BaseModel):
    """Outcome of one transactional sample-bundle ingestion."""

    model_config = ConfigDict(frozen=True, extra="allow")

    status: str
    sample_id: str
    sample_name: str


class Download(BaseModel):
    """Generated artifact content and its transport-independent download metadata."""

    model_config = ConfigDict(frozen=True)

    filename: str
    content: bytes
    media_type: str


class CsvExport(BaseModel):
    """Filtered clinical CSV content generated by the existing finding export rules."""

    model_config = ConfigDict(frozen=True)

    filename: str
    content: str
    row_count: int


class SampleSearch(BaseModel):
    """Explicit sample-catalog search and independent live/reported pagination values."""

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    status: str = "live"
    search_str: str = ""
    search_mode: str = "live"
    live_sort: str = ""
    reported_sort: str = ""
    page: int = Field(default=1, ge=1)
    per_page: int = Field(default=30, ge=1, le=200)
    live_page: int = Field(default=1, ge=1)
    done_page: int = Field(default=1, ge=1)
    live_per_page: int | None = Field(default=None, ge=1, le=200)
    done_per_page: int | None = Field(default=None, ge=1, le=200)
    profile_scope: str | None = None
    panel_type: str | None = None
    panel_tech: str | None = None
    assay_group: str | None = None
    added_from: datetime | None = None
    added_until: datetime | None = None


class SampleMutation(BaseModel):
    """Minimal affected identity and workflow result without disclosing a full sample document."""

    model_config = ConfigDict(frozen=True)

    resource_id: str
    asp_category: str | None = None
    details: dict[str, Any] = Field(default_factory=dict)


class FileArtifact(BaseModel):
    """Validated artifact served by the configured filesystem integration."""

    model_config = ConfigDict(frozen=True)

    path: str
    filename: str
    media_type: str
    text: str | None = None
