#!/usr/bin/env python3
"""Export public SDK signatures and docstrings without initializing a runtime host."""

from __future__ import annotations

import argparse
import importlib
import inspect
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/sdk/reference.md"
MODULES = (
    "coyote3.application.operations",
    "coyote3.application.operations.inputs",
    "coyote3_client",
    "coyote3.config",
    "coyote3_client.resources",
    "coyote3_client.clinical",
    "coyote3_client.endpoints",
    "coyote3_client.async_client",
)
RESOURCE_TYPES = {
    "coyote3_client.resources": ("Resource", "ResourceCollection"),
    "coyote3_client.clinical": (
        "Finding",
        "FindingCollection",
        "VariantCollection",
        "SampleReports",
        "SampleResource",
        "SampleCollection",
    ),
    "coyote3_client.endpoints": ("ApiEndpoint",),
    "coyote3_client.async_client": (
        "AsyncApiEndpoint",
        "AsyncResource",
        "AsyncCollection",
        "AsyncSamples",
        "AsyncSample",
        "AsyncFindings",
        "AsyncVariants",
        "AsyncReports",
    ),
}


def describe_callable(name: str, value: Any) -> list[str]:
    """Render a supported callable's real signature and owned documentation.

    Args:
        name: Public class, function or method name.
        value: Callable inspected without constructing an instance.

    Returns:
        Markdown lines containing the signature and docstring.
    """
    try:
        signature = re.sub(r" at 0x[0-9a-fA-F]+", "", str(inspect.signature(value)))
    except (TypeError, ValueError):
        signature = " (see class documentation)"
    lines = [f"### `{name}`", "", "```python", name + signature, "```", ""]
    documentation = inspect.getdoc(value)
    if documentation:
        lines.extend(["```text", documentation, "```", ""])
    return lines


def render_reference() -> str:
    """Collect supported exports and their declared methods without runtime initialization.

    Returns:
        Deterministic Markdown excluding inherited framework helper methods.
    """
    lines = [
        "# Python SDK reference",
        "",
        "Generated by `scripts/docs/export_sdk_reference.py` from supported exports,",
        "their signatures and docstrings. Edit the Python source and regenerate this page.",
        "",
        "Start with [getting started](getting-started.md),",
        "[application operations](application-sdk.md) or the [remote client](python-client.md).",
        "Internal modules and inherited framework helpers are not additional operations.",
        "",
    ]
    for module_name in MODULES:
        module = importlib.import_module(module_name)
        lines.extend([f"## `{module_name}`", ""])
        for name in sorted(getattr(module, "__all__", RESOURCE_TYPES.get(module_name, ()))):
            value = getattr(module, name)
            if not callable(value):
                continue
            lines.extend(describe_callable(name, value))
            if inspect.isclass(value):
                for method_name, member in sorted(vars(value).items()):
                    if method_name.startswith("_"):
                        continue
                    if isinstance(member, property):
                        lines.extend(
                            [f"#### `{name}.{method_name}`", "", inspect.getdoc(member) or "", ""]
                        )
                    elif isinstance(member, classmethod | staticmethod) or inspect.isfunction(
                        member
                    ):
                        method_lines = describe_callable(
                            f"{name}.{method_name}", getattr(value, method_name)
                        )
                        method_lines[0] = "#" + method_lines[0]
                        lines.extend(method_lines)
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    """Write documentation from the installed library matching the checkout."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the committed reference is stale"
    )
    args = parser.parse_args()
    reference = render_reference()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != reference:
            parser.error("SDK reference is stale; run scripts/docs/export_sdk_reference.py")
        print("[ok] SDK reference matches the supported Python interface")
        return
    OUTPUT.write_text(reference, encoding="utf-8")
    print("[ok] wrote docs/sdk/reference.md")


if __name__ == "__main__":
    main()
